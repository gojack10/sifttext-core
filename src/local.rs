fn reader_state(home: &Path) -> Result<String> {
    use std::path::Component;
    require(
        home.is_absolute()
            && home
                .components()
                .all(|c| matches!(c, Component::RootDir | Component::Normal(_))),
        "reader home must be an absolute canonical path",
    )?;
    require(
        fs::canonicalize(home)? == home,
        "reader home must not traverse symlinks or aliases",
    )?;
    crate::real_dir(home)?;
    let dotgit = home.join(".git");
    crate::real_dir(&dotgit)?;
    require(
        crate::read_regular(&home.join(".gitignore"))? == IGNORE.as_bytes(),
        "not an initialized local knowledge home",
    )?;
    for name in ["refs", "refs/heads"] {
        let path = dotgit.join(name);
        if fs::symlink_metadata(&path).is_ok() {
            crate::real_dir(&path)?;
        }
    }
    for name in [
        "HEAD",
        "config",
        "config.worktree",
        "index",
        "packed-refs",
        "refs/heads/main",
    ] {
        let path = dotgit.join(name);
        if let Ok(meta) = fs::symlink_metadata(&path) {
            use std::os::unix::fs::MetadataExt;
            require(
                meta.is_file() && meta.nlink() == 1,
                "unsafe reader Git file",
            )?;
        }
    }
    require(
        !crate::read_regular(&dotgit.join("HEAD"))?.starts_with(b"ref:"),
        "reader must be detached; branch-owned checkouts are not advanced",
    )?;
    for name in [
        "MERGE_HEAD",
        "CHERRY_PICK_HEAD",
        "REVERT_HEAD",
        "rebase-merge",
        "rebase-apply",
        "info/sparse-checkout",
    ] {
        require(
            fs::symlink_metadata(dotgit.join(name)).is_err(),
            "unfinished or sparse Git reader",
        )?;
    }
    require(
        reader_git(home, &["rev-parse", "--show-toplevel"])?
            == home.to_str().ok_or("non-UTF-8 home")?
            && reader_git(home, &["rev-parse", "--path-format=absolute", "--git-dir"])?
                == dotgit.to_str().ok_or("non-UTF-8 home")?
            && reader_git(
                home,
                &["rev-parse", "--path-format=absolute", "--git-common-dir"],
            )? == dotgit.to_str().ok_or("non-UTF-8 home")?,
        "reader must be an independent Git home root",
    )?;
    require(
        reader_git(home, &["ls-files", "-v"])?
            .lines()
            .all(|line| line.starts_with("H ")),
        "reader index has hidden/sparse edits; preserve files before advancing",
    )?;
    let head = reader_git(home, &["rev-parse", "--verify", "HEAD^{commit}"])?;
    crate::checked_publication::tracked_matches_commit(home, &head, &BTreeSet::new()).map_err(
        |error| {
            format!("reader is dirty or unverifiable; preserve files before advancing: {error}")
        },
    )?;
    require(
        reader_git(
            home,
            &[
                "status",
                "--porcelain=v1",
                "--untracked-files=all",
                "--ignore-submodules=none",
            ],
        )?
        .is_empty(),
        "reader is dirty; preserve authored and untracked work before advancing",
    )?;
    Ok(head)
}

